CREATE TABLE cargo_package_packing_profiles
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    package_id        BIGINT NOT NULL UNIQUE,

    orientation       VARCHAR(100),
    upright_only      BOOLEAN,
    fragility_level   INTEGER,
    stackable         BOOLEAN,

    max_top_load_kg   NUMERIC(10, 2),
    max_layers        INTEGER,
    min_support_ratio NUMERIC(5, 4),

    priority          INTEGER,
    must_load         BOOLEAN,
    packing_group     VARCHAR(100),

    CONSTRAINT fk_packing_profile_package
        FOREIGN KEY (package_id)
            REFERENCES packages (id),

    CONSTRAINT chk_profile_fragility
        CHECK (fragility_level IS NULL OR fragility_level >= 0),

    CONSTRAINT chk_profile_top_load
        CHECK (max_top_load_kg IS NULL OR max_top_load_kg >= 0),

    CONSTRAINT chk_profile_max_layers
        CHECK (max_layers IS NULL OR max_layers >= 1),

    CONSTRAINT chk_profile_support_ratio
        CHECK (
            min_support_ratio IS NULL
                OR min_support_ratio BETWEEN 0 AND 1
            )
);
