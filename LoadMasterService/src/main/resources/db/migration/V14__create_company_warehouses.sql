CREATE TABLE company_warehouses
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    company_id     BIGINT       NOT NULL,
    warehouse_name VARCHAR(255) NOT NULL,
    address        VARCHAR(500) NOT NULL,

    latitude       NUMERIC(10, 7),
    longitude      NUMERIC(10, 7),

    is_default     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_company_warehouses_company
        FOREIGN KEY (company_id)
            REFERENCES companies (id),

    CONSTRAINT chk_company_warehouses_coordinates
        CHECK (
            (latitude IS NULL AND longitude IS NULL)
                OR (
                latitude BETWEEN -90 AND 90
                    AND longitude BETWEEN -180 AND 180
                )
            )
);

CREATE INDEX idx_company_warehouses_company
    ON company_warehouses (company_id);

CREATE UNIQUE INDEX uq_company_warehouse_default
    ON company_warehouses (company_id) WHERE is_default = TRUE;
