@pytest.fixture(scope='module')
def postgres():
    path=os.getenv('LOADMASTER_PERSISTENCE_TEST_SETTINGS')
    if not path:pytest.skip('Opt-in: requires a new dedicated full-schema PostgreSQL test container')
    s=json.loads(Path(path).read_text())
