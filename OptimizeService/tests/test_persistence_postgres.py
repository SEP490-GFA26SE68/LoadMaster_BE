def run_reserved(ctx,result=None,solver=None):
    credit=Mock(deduct_credit=AsyncMock(),refund_credit=AsyncMock())
    if solver is None:solver=Mock(solve=AsyncMock(return_value=result))
    runner=AsyncOptimizationRunner(optimization_client=solver,credit_client=credit)
    asyncio.run(runner.run(ctx['key'],problem=ctx['request'],db=ctx['db']))
    return runner,credit


def counts(ctx):
    db=ctx['db'];job=ctx['job']
    plans=db.query(LoadPlan).filter_by(job_id=job).all()
    placed=db.query(PackagePlacement).filter(PackagePlacement.load_plan_id.in_([p.id for p in plans])).all()
    unplaced=db.query(UnplacedPackage).filter(UnplacedPackage.load_plan_id.in_([p.id for p in plans])).all()
    return plans,placed,unplaced


@pytest.mark.parametrize('partial',[False,True])
def test_real_solver_runner_persists_geometry_uuid_partition_and_billing(reserved,partial):
    c=reserved
    if partial:c['request'].packages[1].allowed_rotations=[]
    solver=OptimizationClient(engine_url='')
    # Observe RUNNING inside execution, using the real solver/persistence otherwise.
    original=solver.solve
    async def observed(req):
        assert c['db'].get(OptimizationJob,c['job']).status=='RUNNING'
        return await original(req)
    solver.solve=observed
    _,credit=run_reserved(c,solver=solver)
    plans,placed,unplaced=counts(c)
    job=c['db'].get(OptimizationJob,c['job']);c['db'].refresh(job)
    assert job.job_uuid==c['key'] and job.status==('PARTIAL' if partial else 'COMPLETED')
    assert len(plans)==1 and len(placed)==(1 if partial else 2) and len(unplaced)==int(partial)
    assert sorted([p.package_id for p in placed]+[u.package_id for u in unplaced])==sorted(c['ids'])
    restored=[PlacementData(package_id=str(p.package_id),x=p.pos_x,y=p.pos_y,z=p.pos_z,
        packed_l=p.packed_length,packed_w=p.packed_width,packed_h=p.packed_height,rotation_type=p.rotation_type) for p in placed]
    assert validate_plan(restored,c['request'].vehicle,{p.id:p for p in c['request'].packages},time.monotonic()+5)==[]
    assert all((p.rotation_type,float(p.packed_length),float(p.packed_width),float(p.packed_height))==(0,40.,30.,25.) for p in placed)
    credit.deduct_credit.assert_not_awaited();credit.refund_credit.assert_not_awaited()
    assert c['db'].execute(text("SELECT count(*) FROM credit_transactions WHERE reference=:ref"),{'ref':c['key']}).scalar()==1
    assert c['db'].execute(text('SELECT balance FROM credit_accounts WHERE id=:id'),{'id':c['account']}).scalar()==98
    # A separate session observes committed rows, not just ORM identity-map state.
    with Session(c['engine']) as other:
        assert other.query(LoadPlan).filter_by(job_id=c['job']).count()==1


