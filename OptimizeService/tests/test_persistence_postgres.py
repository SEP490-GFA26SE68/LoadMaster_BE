def test_duplicate_dispatch_runs_once_and_has_one_committed_plan(reserved):
    c=reserved;barrier=Barrier(2);calls=[]
    async def solve(req):
        calls.append(1)
        return OptimizationClient(engine_url='').solve_in_process(req)
    def worker():
        with Session(c['engine']) as db:
            barrier.wait(timeout=10)
            runner=AsyncOptimizationRunner(optimization_client=Mock(solve=solve),credit_client=Mock())
            asyncio.run(runner.run(c['key'],problem=c['request'],db=db))
    with ThreadPoolExecutor(max_workers=2) as pool:
        futures=[pool.submit(worker) for _ in range(2)]
        for f in futures:f.result(timeout=20)
    c['db'].expire_all()
    assert len(calls)==1 and len(counts(c)[0])==1


@pytest.mark.parametrize('invalid',['partition','boundary','collision','obstacle','stacking','cog','axle','unload'])
def test_runner_revalidates_hard_constraints_before_persistence(reserved,invalid):
    """Acceptance probes: failures identify runtime gaps; never loosen expectations."""
    c=reserved;p,q=c['request'].packages
    boxes=[placement(p,290),placement(q,330)]
    if invalid=='partition':boxes=[boxes[0]]  # missing package, not a DB unique-key rejection
    if invalid=='boundary':boxes[0].x=1000
    if invalid=='collision':boxes[1].x=290
    if invalid=='obstacle':
        from app.dto.optimization.engine.problem_request import ObstacleData
        c['request'].vehicle.obstacles=[ObstacleData(id=1,type='WHEEL_ARCH',x=290,y=100,z=0,length=40,width=30,height=25,load_bearing=False)]
    if invalid=='stacking':boxes[0].z=50
    if invalid=='cog':
        boxes[0].x=550;boxes[1].x=590
    if invalid=='axle':
        c['request'].vehicle.front_axle_limit_kg=1
    if invalid=='unload':
        c['request'].vehicle.door_h=10
    run_reserved(c,EngineOptimizationResponse(placements=boxes))
    assert counts(c)==([],[],[]), 'Invalid engine result reached persistence instead of being rejected'


@pytest.mark.parametrize('code,dims',[(0,(40,30,25)),(1,(30,40,25)),(2,(40,25,30)),(3,(30,25,40)),(4,(25,40,30)),(5,(25,30,40))])
def test_rotation_dimensions_round_trip_in_real_postgres(reserved,code,dims):
    from app.dto.optimization.engine.engine_response import MetricsData
    c=reserved;p,q=c['request'].packages
    p.rotation_allowed=True;p.allowed_rotations=[code]
    box=PlacementData(package_id=p.id,x=310-dims[0]/2,y=120-dims[1]/2,z=0,
        packed_l=dims[0],packed_w=dims[1],packed_h=dims[2],rotation_type=code)
    assert validate_plan([box],c['request'].vehicle,{p.id:p,q.id:q},time.monotonic()+5)==[]
    result=EngineOptimizationResponse(placements=[box],unplaced=[UnplacedData(package_id=q.id,reason='OUT_OF_SPACE')],metrics=MetricsData(packed_count=1))
    run_reserved(c,result)
    plan,placed,unplaced=counts(c)
    assert len(plan)==len(placed)==len(unplaced)==1
    assert plan[0].packed_items_count==1
    row=placed[0]
    assert (row.rotation_type,float(row.packed_length),float(row.packed_width),float(row.packed_height))==(code,*dims)
    with Session(c['engine']) as db:
        reloaded=db.get(PackagePlacement,row.id)
        assert (reloaded.rotation_type,float(reloaded.packed_length),float(reloaded.packed_width),float(reloaded.packed_height))==(code,*dims)


